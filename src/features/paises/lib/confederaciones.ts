export function getConfederacionSeleccion(
  codigo?: string | null,
): string | null {
  const normalizedCode = codigo?.trim().toUpperCase();

  if (!normalizedCode) return null;
  if (CONMEBOL_CODES.has(normalizedCode)) return "CONMEBOL";
  if (CONCACAF_CODES.has(normalizedCode)) return "CONCACAF";
  if (UEFA_CODES.has(normalizedCode)) return "UEFA";
  if (AFC_CODES.has(normalizedCode)) return "AFC";
  if (CAF_CODES.has(normalizedCode)) return "CAF";

  return null;
}
